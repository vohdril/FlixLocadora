    public static string? Constraints(Slice s)
    {
        var e = s.Entity;
        if (e.Uniques.Count == 0 && s.Blockers.Count == 0 && e.ForeignKeys.Count == 0)
            return null;

        var codes = new StringBuilder();
        var maps = new StringBuilder();

        // A foreign key violated on INSERT/UPDATE of THIS table = the referenced row does not exist (422, on the field).
        foreach (var fk in e.ForeignKeys.Where(fk => fk.ConstraintName.Length > 0))
        {
            var target = fk.Property.EndsWith("Id", StringComparison.Ordinal) && fk.Property.Length > 2 ? fk.Property[..^2] : fk.Principal;
            codes.AppendLine($"    public static readonly ErrorCode {target}NotFound = new(\"{s.Prefix}_{Naming.UpperSnake(target)}_NOT_FOUND\", \"The {Naming.Spaced(target)} does not exist.\", ErrorKind.BusinessRule);");
            maps.AppendLine($"        Map(\"{fk.ConstraintName}\", {s.Name}Errors.{target}NotFound, field: \"{Naming.Camel(fk.Property)}\", statement: \"INSERT\");");
            maps.AppendLine($"        Map(\"{fk.ConstraintName}\", {s.Name}Errors.{target}NotFound, field: \"{Naming.Camel(fk.Property)}\", statement: \"UPDATE\");");
        }

        foreach (var unique in e.Uniques)
        {
            codes.AppendLine($"    public static readonly ErrorCode {unique.Property}AlreadyExists = new(\"{s.Prefix}_{Naming.UpperSnake(unique.Property)}_ALREADY_EXISTS\", \"{Naming.AOrAn(s.Spaced)} {s.Spaced} with this {Naming.Spaced(unique.Property)} already exists.\", ErrorKind.Conflict);");
            maps.AppendLine($"        Map(\"{unique.ConstraintName}\", {s.Name}Errors.{unique.Property}AlreadyExists, field: \"{Naming.Camel(unique.Property)}\");");
        }

        foreach (var blocker in s.Blockers)
        {
            var plural = Naming.Plural(blocker.Key);
            codes.AppendLine($"    public static readonly ErrorCode Has{plural} = new(\"{s.Prefix}_HAS_{Naming.UpperSnake(plural)}\", \"The {s.Spaced} is referenced by {Naming.Spaced(plural)}: it cannot be deleted.\", ErrorKind.Conflict);");
            foreach (var reference in blocker)
                maps.AppendLine($"        Map(\"{reference.ConstraintName}\", {s.Name}Errors.Has{plural}, statement: \"DELETE\");");
        }

        return GeneratedHeader + $$"""
            using {{s.Api}}.Business.Common;

            namespace {{s.Namespace}};

            public static partial class {{s.Name}}Errors
            {
            {{codes.ToString().TrimEnd()}}
            }

            /// <summary>Database constraints of {{e.Table}} → typed errors (Infra/Errors/DbExceptionHandler).</summary>
            public sealed partial class {{s.Name}}Constraints : ConstraintErrorCatalog
            {
                public {{s.Name}}Constraints()
                {
            {{maps.ToString().TrimEnd()}}
                }
            }

            """;
    }

