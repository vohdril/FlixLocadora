using System.Text;

namespace CrudGen;

/// <summary>Everything a slice needs to know about its entity, already named.</summary>
public sealed record Slice(EntityInfo Entity, string Root)
{
    public string Name => Entity.Name;
    public string Feature => Naming.Plural(Name);
    public string Route => Naming.Kebab(Feature);
    public string Prefix => Naming.UpperSnake(Name);
    public string Spaced => Naming.Spaced(Name);
    public string Api => $"{Root}.Api";
    public string Namespace => $"{Api}.Business.{Feature}";
    public PropInfo Key => Entity.Key ?? throw new InvalidOperationException($"{Name} has no single-column key.");

    /// <summary>Referencing entities WITHOUT cascade: their rows block a delete (with cascade they go along).</summary>
    public IReadOnlyList<IGrouping<string, ReferenceInfo>> Blockers => Entity.ReferencedBy
        .Where(r => !r.Cascade)
        .GroupBy(r => r.Entity)
        .OrderBy(g => g.Key, StringComparer.Ordinal)
        .ToList();
}

