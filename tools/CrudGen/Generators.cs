    public static string Diagram(IReadOnlyList<EntityInfo> entities)
    {
        var text = new StringBuilder();
        text.AppendLine("# Modelo de dados");
        text.AppendLine();
        text.AppendLine("_Gerado pelo CrudGen a partir do banco (o mesmo modelo que o scaffold lê). Não edite: rode `scripts/crudgen.ps1`._");
        text.AppendLine();
        text.AppendLine("```mermaid");
        text.AppendLine("erDiagram");
        foreach (var entity in entities)
        {
            text.AppendLine($"    {entity.Name} {{");
            foreach (var p in entity.Properties)
            {
                var marker = p.IsKey ? " PK" : p.IsForeignKey ? " FK" : "";
                var note = p.IsNullable ? " \"nullable\"" : "";
                text.AppendLine($"        {p.Type.TrimEnd('?').Replace("[]", "_array")} {p.Name}{marker}{note}");
            }
            text.AppendLine("    }");
        }

        foreach (var entity in entities)
        {
            foreach (var fk in entity.ForeignKeys)
                text.AppendLine($"    {fk.Principal} ||--o{{ {entity.Name} : \"{fk.ConstraintName}\"");
        }

        text.AppendLine("```");
        return text.ToString();
    }

    private static string Parameters(IEnumerable<PropInfo> properties, string? extra = null)
    {
        var list = properties.Select(p => $"{p.CsType} {p.Name}").ToList();
        if (extra is not null)
            list.Add(extra);
        return string.Join(", ", list);
    }

    private static string Rules(IEnumerable<PropInfo> properties)
    {
        var lines = new List<string>();
        foreach (var p in properties)
        {
            var chain = new List<string>();
            if (p.IsString && !p.IsNullable)
                chain.Add("NotEmpty()");
            if (p.IsString && p.MaxLength is { } max)
                chain.Add($"MaximumLength({max})");
            if (p.Type.TrimEnd('?') == "decimal" && p is { Precision: { } precision, Scale: { } scale })
                chain.Add($"PrecisionScale({precision}, {scale}, true)");
            if (p.IsForeignKey && p.Type.TrimEnd('?') is "int" or "long" or "short")
                chain.Add("GreaterThan(0)");

            if (chain.Count > 0)
                lines.Add($"        RuleFor(x => x.{p.Name}).{string.Join(".", chain)};");
        }

        return string.Join("\n", lines);
    }
