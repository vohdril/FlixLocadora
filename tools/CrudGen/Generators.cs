    public static string Converter(Slice s)
    {
        var e = s.Entity;
        var toEntity = new StringBuilder();
        foreach (var p in e.Properties.Where(p => !p.InCreate))
            toEntity.AppendLine($"    [MapperIgnoreTarget(nameof({s.Name}.{p.Name}))]");
        foreach (var n in e.Navigations)
            toEntity.AppendLine($"    [MapperIgnoreTarget(nameof({s.Name}.{n}))]");

        var apply = new StringBuilder();
        foreach (var p in e.Properties.Where(p => !p.InUpdate))
            apply.AppendLine($"    [MapperIgnoreTarget(nameof({s.Name}.{p.Name}))]");
        foreach (var n in e.Navigations)
            apply.AppendLine($"    [MapperIgnoreTarget(nameof({s.Name}.{n}))]");
        if (e.RowVersion is not null)
            apply.AppendLine($"    [MapperIgnoreSource(nameof(Update{s.Name}Request.Version))]   // checked by the service (optimistic concurrency)");

        var toResponse = new StringBuilder();
        foreach (var n in e.Navigations)
            toResponse.AppendLine($"    [MapperIgnoreSource(nameof({s.Name}.{n}))]");
        if (e.RowVersion is { } version)
            toResponse.AppendLine($"    [MapProperty(nameof({s.Name}.{version.Name}), nameof({s.Name}Response.Version), Use = nameof(VersionOf))]");

        var helpers = e.RowVersion is not null
            ? "\n\n    [UserMapping(Default = false)]\n    private static string VersionOf(byte[] rowVersion) => RowVersion.ToVersion(rowVersion);"
            : "";

        return OwnedHeader + $$"""
            using Riok.Mapperly.Abstractions;
            using {{s.Api}}.Business.Common;
            using {{s.Api}}.Data.Entities;

            namespace {{s.Namespace}};

            /// <summary>{{s.Name}} ⇄ contracts (Mapperly: a member without a counterpart is a build error).</summary>
            [Mapper(AutoUserMappings = false)]
            public sealed partial class {{s.Name}}Converter : IEntityConverter<{{s.Name}}, Create{{s.Name}}Request, Update{{s.Name}}Request, {{s.Name}}Response>
            {
            {{toEntity}}    public partial {{s.Name}} ToEntity(Create{{s.Name}}Request request);

            {{apply}}    public partial void Apply(Update{{s.Name}}Request request, [MappingTarget] {{s.Name}} entity);

            {{toResponse}}    public partial {{s.Name}}Response ToResponse({{s.Name}} entity);{{helpers}}
            }

            """;
    }

    public static string Service(Slice s)
    {
        var e = s.Entity;
        var key = s.Key;
        var parameters = new List<string> { $"IRepository<{s.Name}> {Naming.Camel(Naming.Plural(s.Name))}" };
        foreach (var blocker in s.Blockers.Where(b => b.Key != s.Name))
            parameters.Add($"IRepository<{blocker.Key}> {Naming.Camel(Naming.Plural(blocker.Key))}");
        parameters.Add("IUnitOfWork unitOfWork");
        parameters.Add($"IEntityConverter<{s.Name}, Create{s.Name}Request, Update{s.Name}Request, {s.Name}Response> converter");
        if (e.Audit is not null)
            parameters.Add("TimeProvider clock");

        var body = new StringBuilder();

        var searchable = e.Properties.Where(p => p.IsString && !p.IsKey && (p.MaxLength is null or <= 400)).Take(2).ToList();
        if (searchable.Count > 0)
        {
            var condition = string.Join(" || ", searchable.Select(p => p.IsNullable ? $"(e.{p.Name} != null && e.{p.Name}.Contains(search))" : $"e.{p.Name}.Contains(search)"));
            body.Append($$"""

                protected override IQueryable<{{s.Name}}> Filter(IQueryable<{{s.Name}}> query, {{s.Name}}ListQuery parameters)
                {
                    if (string.IsNullOrWhiteSpace(parameters.Search))
                        return query;

                    var search = parameters.Search.Trim();
                    return query.Where(e => {{condition}});
                }

            """);
        }

        var orderBy = e.Properties.FirstOrDefault(p => p.IsString && !p.IsKey && !p.IsNullable);
        if (orderBy is not null)
        {
            body.Append($$"""

                protected override IOrderedQueryable<{{s.Name}}> Order(IQueryable<{{s.Name}}> query) => query.OrderBy(e => e.{{orderBy.Name}}).ThenBy(e => e.{{key.Name}});

            """);
        }

        var updating = new List<string>();
        if (e.Audit is { } audit)
            updating.Add(audit.Type.StartsWith("DateTimeOffset") ? $"entity.{audit.Name} = clock.GetUtcNow();" : $"entity.{audit.Name} = clock.GetUtcNow().UtcDateTime;");
        if (e.RowVersion is not null)
            updating.Add("Repository.ExpectVersion(entity, RowVersion.FromVersion(request.Version));");
        if (updating.Count > 0)
        {
            body.Append($$"""

                protected override void OnUpdating(Update{{s.Name}}Request request, {{s.Name}} entity)
                {
                    {{string.Join("\n        ", updating)}}
                }

            """);
        }

        if (e.Uniques.Count > 0)
        {
            body.Append(UniqueCheck(s, "Create", self: false));
            body.Append(UniqueCheck(s, "Update", self: true));
        }

        if (s.Blockers.Count > 0)
        {
            var checks = new StringBuilder();
            foreach (var blocker in s.Blockers)
            {
                var repository = blocker.Key == s.Name ? "Repository" : Naming.Camel(Naming.Plural(blocker.Key));
                var condition = string.Join(" || ", blocker.Select(r => $"r.{r.Property} == entity.{key.Name}"));
                checks.Append($$"""
                        if (await {{repository}}.Query().AnyAsync(r => {{condition}}, ct))
                            return Responses.Fail({{s.Name}}Errors.Has{{Naming.Plural(blocker.Key)}});


                """);
            }

            body.Append($$"""

                protected override async Task<ApiResponse?> CheckDeleteAsync({{s.Name}} entity, CancellationToken ct)
                {
            {{checks}}        return null;
                }

            """);
        }

        var usings = new List<string>();
        if (e.Uniques.Count > 0 || s.Blockers.Count > 0)
            usings.Add("using Microsoft.EntityFrameworkCore;");
        usings.AddRange([$"using {s.Api}.Business.Common;", $"using {s.Api}.Data;", $"using {s.Api}.Data.Entities;", $"using {s.Api}.Data.Repositories;"]);

        return OwnedHeader + $$"""
            {{string.Join("\n", usings)}}

            namespace {{s.Namespace}};

            public interface I{{s.Name}}Service : ICrudService<{{key.Type}}, {{s.Name}}ListQuery, Create{{s.Name}}Request, Update{{s.Name}}Request, {{s.Name}}Response>;

            /// <summary>
            /// {{s.Feature}} — the CRUD comes from CrudService; business rules go in the hooks below
            /// (Filter, Order, OnCreating/OnUpdating, Check*). Unique columns are pre-checked for a friendly 409;
            /// the database constraints stay the real guarantee ({{s.Name}}Constraints).
            /// </summary>
            public sealed class {{s.Name}}Service(
                {{string.Join(",\n    ", parameters)}})
                : CrudService<{{s.Name}}, {{key.Type}}, {{s.Name}}ListQuery, Create{{s.Name}}Request, Update{{s.Name}}Request, {{s.Name}}Response>({{Naming.Camel(Naming.Plural(s.Name))}}, unitOfWork, converter),
                  I{{s.Name}}Service
            {
            {{body.ToString().Trim('\n')}}
            }

            """.Replace("{\n\n}", "{\n}");
    }

    private static string UniqueCheck(Slice s, string operation, bool self)
    {
        var checks = new StringBuilder();
        foreach (var unique in s.Entity.Uniques)
        {
            var property = s.Entity.Properties.Single(p => p.Name == unique.Property);
            var condition = $"e.{unique.Property} == entity.{unique.Property}" + (self ? $" && e.{s.Key.Name} != entity.{s.Key.Name}" : "");
            var guard = property.IsNullable ? $"entity.{unique.Property} != null && " : "";
            checks.Append($$"""
                    if ({{guard}}await Repository.Query().AnyAsync(e => {{condition}}, ct))
                        return Responses.Fail({{s.Name}}Errors.{{unique.Property}}AlreadyExists, field: "{{Naming.Camel(unique.Property)}}");


            """);
        }

        return $$"""

            protected override async Task<ApiResponse?> Check{{operation}}Async({{operation}}{{s.Name}}Request request, {{s.Name}} entity, CancellationToken ct)
            {
        {{checks}}        return null;
            }

        """;
    }

