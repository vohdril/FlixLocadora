using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;

namespace FlixLocadora.Api.Data.Repositories;

/// <summary>
/// Generic repository over the scoped AppDbContext. It does NOT save — the unit of work does (IUnitOfWork), so
/// several repositories can take part in one SaveChanges. Exceptions are never swallowed: the base projects'
/// repository answered `false` to every failure (catch → return false) and the real error never reached a log.
/// </summary>
public interface IRepository<TEntity> : IRepository
    where TEntity : class, IEntity
{
    /// <summary>Read-only query (no tracking).</summary>
    IQueryable<TEntity> Query();

    /// <summary>Tracked query — for entities that will be changed and saved.</summary>
    IQueryable<TEntity> QueryTracked();

    /// <summary>Filters by the primary key (single-column keys), as a SQL parameter.</summary>
    IQueryable<TEntity> WhereKey<TKey>(IQueryable<TEntity> query, TKey key)
        where TKey : notnull;

    /// <summary>Deterministic order by the primary key — paging needs a stable order.</summary>
    IOrderedQueryable<TEntity> OrderByKey(IQueryable<TEntity> query);

    /// <summary>Primary key of an entity (after SaveChanges, the value generated by the database).</summary>
    TKey KeyOf<TKey>(TEntity entity);

    /// <summary>
    /// Optimistic concurrency: the next SaveChanges only succeeds if the row still has this rowversion
    /// (the value the client read). Otherwise EF throws DbUpdateConcurrencyException → 409 CONCURRENCY_CONFLICT.
    /// </summary>
    void ExpectVersion(TEntity entity, byte[] rowVersion);

    /// <summary>
    /// Pessimistic lock of ONE row: loads the entity (tracked) and keeps its row locked (UPDLOCK) until the
    /// transaction ends — a second caller waits and then reads the committed value, instead of both deciding on the
    /// same old value (a double-click on "return" would put the copy back twice). Only inside IUnitOfWork.InTransactionAsync.
    /// </summary>
    Task<TEntity?> FindForUpdateAsync<TKey>(TKey key, CancellationToken ct)
        where TKey : notnull;

    void Add(TEntity entity);

    void Remove(TEntity entity);
}

public class Repository<TEntity>(AppDbContext db) : IRepository<TEntity>
    where TEntity : class, IEntity
{
    protected AppDbContext Db { get; } = db;

    protected DbSet<TEntity> Set => Db.Set<TEntity>();

    public IQueryable<TEntity> Query() => Set.AsNoTracking();

    public IQueryable<TEntity> QueryTracked() => Set;

    public IQueryable<TEntity> WhereKey<TKey>(IQueryable<TEntity> query, TKey key)
        where TKey : notnull
    {
        var (entity, column) = KeyColumn();

        // A member of a captured object, not a constant: EF turns it into a SQL parameter (one plan for every id).
        Expression value = Expression.Property(Expression.Constant(new KeyValue<TKey>(key)), nameof(KeyValue<TKey>.Value));
        if (value.Type != column.Type)
            value = Expression.Convert(value, column.Type);

        return query.Where(Expression.Lambda<Func<TEntity, bool>>(Expression.Equal(column, value), entity));
    }

    public IOrderedQueryable<TEntity> OrderByKey(IQueryable<TEntity> query)
    {
        var (entity, column) = KeyColumn();
        var orderBy = OrderByMethod.MakeGenericMethod(typeof(TEntity), column.Type);
        return (IOrderedQueryable<TEntity>)orderBy.Invoke(null, [query, Expression.Lambda(column, entity)])!;
    }

    public TKey KeyOf<TKey>(TEntity entity) => (TKey)Db.Entry(entity).Property(KeyProperty().Name).CurrentValue!;

    public void ExpectVersion(TEntity entity, byte[] rowVersion)
    {
        var token = Db.Model.FindEntityType(typeof(TEntity))?.GetProperties().SingleOrDefault(p => p.IsConcurrencyToken)
            ?? throw new InvalidOperationException($"{typeof(TEntity).Name} has no concurrency token (rowversion column).");

        Db.Entry(entity).Property(token.Name).OriginalValue = rowVersion;
    }

    public Task<TEntity?> FindForUpdateAsync<TKey>(TKey key, CancellationToken ct)
        where TKey : notnull
    {
        if (Db.Database.CurrentTransaction is null)
            throw new InvalidOperationException("FindForUpdateAsync holds the lock until the transaction ends: call it inside IUnitOfWork.InTransactionAsync.");

        // The table name comes from the EF model, never from input. ROWLOCK + the primary-key seek lock only this row.
        var entityType = Db.Model.FindEntityType(typeof(TEntity))!;
        var sql = "SELECT * FROM [" + entityType.GetSchema() + "].[" + entityType.GetTableName() + "] WITH (UPDLOCK, ROWLOCK)";

        return WhereKey(Set.FromSqlRaw(sql), key).FirstOrDefaultAsync(ct);
    }

    public void Add(TEntity entity) => Set.Add(entity);

    public void Remove(TEntity entity) => Set.Remove(entity);

    private (ParameterExpression Entity, MethodCallExpression Column) KeyColumn()
    {
        var key = KeyProperty();
        var entity = Expression.Parameter(typeof(TEntity), "e");
        var column = Expression.Call(typeof(EF), nameof(EF.Property), [key.ClrType], entity, Expression.Constant(key.Name));
        return (entity, column);
    }

    private IProperty KeyProperty()
        => Db.Model.FindEntityType(typeof(TEntity))?.FindPrimaryKey()?.Properties is [var single]
            ? single
            : throw new InvalidOperationException($"{typeof(TEntity).Name} needs a single-column primary key to use the generic repository.");

    private static readonly System.Reflection.MethodInfo OrderByMethod = typeof(Queryable).GetMethods()
        .Single(m => m.Name == nameof(Queryable.OrderBy) && m.GetParameters().Length == 2);

    private sealed record KeyValue<T>(T Value);
}
