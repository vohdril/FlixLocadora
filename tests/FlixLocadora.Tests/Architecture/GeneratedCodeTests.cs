using FlixLocadora.Tests.Support;

namespace FlixLocadora.Tests.Architecture;

/// <summary>
/// Generated folders belong to their generators: Data/Generated to scripts/scaffold.ps1, Business/*/Generated to
/// scripts/crudgen.ps1. Nobody creates or hand-edits files there (the next run would erase the change).
/// </summary>
public class GeneratedCodeTests
{
    [Fact]
    public void Every_file_under_Data_Generated_comes_from_the_scaffold()
        => AssertGenerated(Path.Combine(RepositoryPaths.Api, "Data", "Generated"));

    [Fact]
    public void Every_file_under_Business_Generated_comes_from_CrudGen()
    {
        foreach (var folder in Directory.EnumerateDirectories(Path.Combine(RepositoryPaths.Api, "Business"), "Generated", SearchOption.AllDirectories))
            AssertGenerated(folder);
    }

    private static void AssertGenerated(string folder)
    {
        var handWritten = Directory.EnumerateFiles(folder, "*.cs", SearchOption.AllDirectories)
            .Where(file => !File.ReadLines(file).First().TrimStart('﻿').StartsWith("// <auto-generated>", StringComparison.Ordinal))
            .Select(file => Path.GetRelativePath(RepositoryPaths.Api, file))
            .ToList();

        Assert.True(handWritten.Count == 0, "Files in a Generated folder without the generator header: " + string.Join(", ", handWritten));
    }
}
